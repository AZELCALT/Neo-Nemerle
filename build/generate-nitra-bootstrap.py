#!/usr/bin/env python3
"""Embed unmodified pinned Nitra declaration grammars; no upstream binaries used."""
import hashlib,json,pathlib,subprocess
repo=pathlib.Path(__file__).resolve().parents[1]
ref=repo.parent/'nitra-reference'; target=repo/'ncc/Nemerle/Compiler/nitra_bootstrap.n'
commit='b287b8a42237fac4d993444e7e3af9240b601503'
actual=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ref,text=True).strip()
if actual!=commit: raise SystemExit(f'Expected {commit}, got {actual}')
files=['Nitra/Nitra.Runtime/Core.nitra','Nitra/Nitra.Runtime/CStyleComments.nitra','Nitra/Nitra.Grammar/NitraLiterals.nitra','Nitra/Nitra.Grammar/NitraSyntax.nitra']
lines=['using Nemerle.Compiler.nitra_syntax;', 'using Nemerle.Compiler.NitraSyntaxModel;', '// Generated by build/generate-nitra-bootstrap.py. Do not edit.', '// Nitra grammar text Copyright (c) JetBrains. BSD-3-Clause.', '// See grammar/NITRA-NOTICES.txt and NITRA-BASELINE.json.', 'internal module NitraBootstrap {', 'public Documents() : array[NitraDocument] { array[']
manifest={'commit':commit,'source':'https://github.com/JetBrains/Nitra','files':{}}
for i,name in enumerate(files):
 raw=(ref/name).read_bytes();manifest['files'][name]=hashlib.sha256(raw).hexdigest()
 text=raw.decode('utf-8-sig')
 # Keep exact CR/LF and escaped source spelling; grammar source is data.
 literal=json.dumps(text,ensure_ascii=True)
 lines.append((',' if i else '')+' NitraSyntax.ReadDefinitions('+literal+','+json.dumps(name)+')')
lines+= ['] }', '}']
target.write_text('\n'.join(lines)+'\n')
(repo/'grammar/NITRA-BASELINE.json').write_text(json.dumps(manifest,indent=2)+'\n')
(repo/'grammar/NITRA-NOTICES.txt').write_text((ref/'License.txt').read_bytes().decode('cp1252'))
print(target)
